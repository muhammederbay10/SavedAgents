"""Builds a small synthetic clip set, so spike tests need no real media and no network."""

import hashlib
import io
import json
import wave
from pathlib import Path

from scripts.spikes.model_choices.fleurs import Provenance, SampleProvenance

LANGUAGES = ("en_us", "tr_tr", "ja_jp")
SENTENCE_IDS = (11, 22)
SAMPLE_RATE_HZ = 16000
CLIP_SECONDS = 1.5
REVISION = "0000000000000000000000000000000000000000"


def reference_for(language: str, sentence_id: int) -> str:
    return f"synthetic sentence {sentence_id} spoken in {language}"


def wav_bytes(seconds: float = CLIP_SECONDS, fill: int = 0) -> bytes:
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as wav_file:
        wav_file.setnchannels(1)
        wav_file.setsampwidth(2)
        wav_file.setframerate(SAMPLE_RATE_HZ)
        wav_file.writeframes(bytes([fill, 0]) * int(SAMPLE_RATE_HZ * seconds))
    return buffer.getvalue()


def write_clip_set(directory: Path) -> Provenance:
    """Write a manifest and one WAV per (language, sentence id); return the matching provenance."""
    directory.mkdir(parents=True, exist_ok=True)
    manifest_samples = []
    provenance_samples = []
    for fill, (language, sentence_id) in enumerate(
        (language, sentence_id) for language in LANGUAGES for sentence_id in SENTENCE_IDS
    ):
        audio = wav_bytes(fill=fill)
        name = f"{language}-{sentence_id}.wav"
        (directory / name).write_bytes(audio)
        reference = reference_for(language, sentence_id)
        manifest_samples.append(
            {
                "language": language,
                "id": sentence_id,
                "reference_raw": reference,
                "audio_file": f"/somewhere/else/{name}",
            }
        )
        provenance_samples.append(
            SampleProvenance(
                language=language,
                id=sentence_id,
                original_file=f"original-{name}",
                sha256_pcm_wav=hashlib.sha256(audio).hexdigest(),
                sha256_reference_utf8=hashlib.sha256(reference.encode("utf-8")).hexdigest(),
                duration_s=CLIP_SECONDS,
            )
        )
    manifest = {
        "dataset": "synthetic/clips",
        "revision": REVISION,
        "split": "test",
        "samples": manifest_samples,
    }
    (directory / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    return Provenance(
        dataset="synthetic/clips",
        source="generated by the test",
        revision=REVISION,
        split="test",
        license="none",
        attribution="none",
        audio_preprocessing="none",
        aligned_ids=list(SENTENCE_IDS),
        samples=provenance_samples,
    )
